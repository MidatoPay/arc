// Exportado para chequear que todos los idiomas tengan las mismas claves.
export { translations };

function getPath(obj, path) {
  return path.split(".").reduce((o, k) => (o ? o[k] : undefined), obj);
}

/** Idiomas disponibles en el selector. El orden es el del dropdown. */
export const LANGUAGES = [
  { id: "es", label: "Español" },
  { id: "en", label: "English" },
  { id: "zh", label: "中文（简体）" },
];
const LANGUAGE_IDS = new Set(LANGUAGES.map((l) => l.id));

/** Una clave que falte en un idioma usa el inglés (y luego la ruta), nunca rompe la pantalla. */
function lookup(lang, path) {
  const val = getPath(translations[lang], path);
  return val === undefined && lang !== "en" ? getPath(translations.en, path) : val;
}

function makeT(lang) {
  return (path, ...args) => {
    const val = lookup(lang, path);
    if (typeof val === "function") return val(...args);
    if (val === undefined) return path;
    return val;
  };
}

const makeValue = (lang, setLang) => ({
  lang, setLang, t: makeT(lang), locale: localeFor(lang),
  has: (path) => getPath(translations[lang], path) !== undefined || getPath(translations.en, path) !== undefined,
});

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      return LANGUAGE_IDS.has(saved) ? saved : "en";
    } catch {
      return "en";
    }
  });

  const setLang = (l) => {
    if (!LANGUAGE_IDS.has(l)) return;
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {}
  };

  useEffect(() => {
    // Lectores de pantalla y traducción del navegador usan el idioma real de la página.
    if (typeof document !== "undefined") document.documentElement.lang = lang === "zh" ? "zh-Hans" : lang;
  }, [lang]);

  const value = useMemo(() => makeValue(lang, setLang), [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within a LanguageProvider");
  return ctx;
}

const SPANISH_FALLBACK = makeValue("es", () => {});
/**
 * Como useLanguage, pero sin provider devuelve español en lugar de fallar.
 * Lo usan componentes de dinero (aprobación, recibo, cobro) que los tests renderizan de forma aislada.
 */
export function useOptionalLanguage() {
  return useContext(LanguageContext) || SPANISH_FALLBACK;
}
